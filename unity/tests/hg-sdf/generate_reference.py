"""Generate the numeric C# oracle directly from the pinned upstream GLSL.

Only syntax/types are translated; upstream conditionals and formulas are retained.
Run from any directory after changing the pinned reference source.
"""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
source = (HERE / 'hg_sdf.glsl').read_text()
source = re.sub(r'//[^\n]*', '', source)
source = re.sub(r'^#.*$', '', source, flags=re.M)
source = source[source.index('float sgn'):]
source = "\n".join(line.rstrip() for line in source.splitlines())
source = re.sub(r'const vec3 GDFVectors\[19\] = vec3\[\]\((.*?)\);', r'static readonly Ref3[] GDFVectors = new Ref3[]{\1};', source, flags=re.S)
for n in [2,3,4]:
    source = re.sub(r'\bvec'+str(n)+r'\s*\(', 'new Ref'+str(n)+'(', source)
    source = re.sub(r'\bvec'+str(n)+r'\b', 'Ref'+str(n), source)
source = source.replace('inout ', 'ref ')
source = re.sub(r'^(float|Ref[234]|void) (\w+)\s*\(', r'public static \1 \2(', source, flags=re.M)
for name in ['pR','pR45','pMod1','pModMirror1','pModSingle1','pModInterval1','pModPolar','pMod2','pModMirror2','pModGrid2','pMod3','pMirror','pMirrorOctant','pReflect']:
    source = re.sub(r'\b'+name+r'\((?!ref )', name+'(ref ', source)
source = re.sub(r'(?<![\w.])(\d+\.\d*|\.\d+)(?![\w.])', r'\1f', source)
source = re.sub(r'(\d+)\.f\b', r'\1.0f', source)
# GLSL integer-looking arguments to sqrt must resolve to the float helper.
source = 'static partial class HgReference\n{\nconst float PI = MathF.PI, TAU = 2*PI;\nstatic readonly float PHI = MathF.Sqrt(5)*0.5f+0.5f;\n'+source+'\n}\n'
(HERE / 'HgReference.Generated.cs').write_text('// Generated from hg_sdf.glsl; do not edit. Mercury MIT notice is retained there.\nusing System;\nusing HgReferenceTypes;\n'+source)
vectors = (HERE.parent.parent/'com.icosa.fidget/Runtime/ExpressionVectors.cs').read_text()
vectors = vectors.replace('namespace Icosa.Fidget','namespace HgReferenceTypes')
for n in [2,3,4]: vectors = vectors.replace('Expression'+str(n),'Ref'+str(n))
vectors = vectors.replace('Expression','float')
(HERE/'ReferenceVectors.Generated.cs').write_text('// Generated by generate_reference.py.\n'+vectors)
